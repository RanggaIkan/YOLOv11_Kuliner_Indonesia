-- 1. Master table of 12 Indonesian culinary classes (total 600 dataset images)
create table if not exists public.culinary_classes (
    id bigint generated by default as identity primary key,
    name text not null unique,
    slug text not null unique,
    region_origin text not null,
    category text not null,
    avg_calories integer not null default 0 check (avg_calories >= 0),
    dataset_count integer not null default 50 check (dataset_count >= 0),
    description text not null default '',
    created_at timestamptz not null default now()
);

-- 2. Detection / Counting / Tracking / Region Counter sessions
create table if not exists public.detection_sessions (
    id bigint generated by default as identity primary key,
    media_name text not null,
    media_type text not null check (media_type in ('image', 'video')),
    model_name text not null default 'yolo11n-culinary-best.pt',
    enhancement_method text not null default 'clahe',
    mode text not null check (mode in ('counting', 'tracking')),
    total_detected integer not null default 0 check (total_detected >= 0),
    region_inside_count integer not null default 0 check (region_inside_count >= 0),
    region_outside_count integer not null default 0 check (region_outside_count >= 0),
    avg_confidence numeric(5, 4) not null default 0.0000 check (avg_confidence >= 0.0 and avg_confidence <= 1.0),
    inference_ms numeric(8, 2) not null default 0.00 check (inference_ms >= 0.0),
    class_breakdown jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);

-- 3. Before vs After Image Enhancement benchmark comparisons
create table if not exists public.enhancement_comparisons (
    id bigint generated by default as identity primary key,
    session_id bigint references public.detection_sessions(id) on delete set null,
    image_name text not null,
    ground_truth_count integer not null default 0 check (ground_truth_count >= 0),
    before_count integer not null default 0 check (before_count >= 0),
    before_conf numeric(5, 4) not null default 0.0000 check (before_conf >= 0.0 and before_conf <= 1.0),
    he_count integer not null default 0 check (he_count >= 0),
    he_conf numeric(5, 4) not null default 0.0000 check (he_conf >= 0.0 and he_conf <= 1.0),
    clahe_count integer not null default 0 check (clahe_count >= 0),
    clahe_conf numeric(5, 4) not null default 0.0000 check (clahe_conf >= 0.0 and clahe_conf <= 1.0),
    cs_count integer not null default 0 check (cs_count >= 0),
    cs_conf numeric(5, 4) not null default 0.0000 check (cs_conf >= 0.0 and cs_conf <= 1.0),
    brightness_count integer not null default 0 check (brightness_count >= 0),
    brightness_conf numeric(5, 4) not null default 0.0000 check (brightness_conf >= 0.0 and brightness_conf <= 1.0),
    best_method text not null default 'clahe',
    conf_improvement_pct numeric(6, 2) not null default 0.00,
    psnr_db numeric(6, 2) not null default 0.00 check (psnr_db >= 0.0),
    created_at timestamptz not null default now()
);

-- Indexes on foreign keys and created_at for fast JOINs, cascades, and sorting
create index if not exists idx_culinary_classes_created_at
    on public.culinary_classes (created_at desc);

create index if not exists idx_detection_sessions_created_at
    on public.detection_sessions (created_at desc);

create index if not exists idx_enhancement_comparisons_session_id
    on public.enhancement_comparisons (session_id);

create index if not exists idx_enhancement_comparisons_created_at
    on public.enhancement_comparisons (created_at desc);

-- Enable Row Level Security (RLS) on all tables in the exposed public schema
alter table public.culinary_classes enable row level security;
alter table public.detection_sessions enable row level security;
alter table public.enhancement_comparisons enable row level security;

-- Explicit least-privilege Data API grants (SELECT & INSERT only; no UPDATE/DELETE)
grant usage on schema public to anon, authenticated;
grant select, insert on table public.culinary_classes to anon, authenticated;
grant select, insert on table public.detection_sessions to anon, authenticated;
grant select, insert on table public.enhancement_comparisons to anon, authenticated;
grant usage, select on sequence public.culinary_classes_id_seq to anon, authenticated;
grant usage, select on sequence public.detection_sessions_id_seq to anon, authenticated;
grant usage, select on sequence public.enhancement_comparisons_id_seq to anon, authenticated;

-- RLS Policies using explicit TO anon, authenticated (never auth.role())
create policy "Allow anon and authenticated read culinary_classes"
    on public.culinary_classes
    for select
    to anon, authenticated
    using (true);

create policy "Allow anon and authenticated insert culinary_classes"
    on public.culinary_classes
    for insert
    to anon, authenticated
    with check (
        char_length(trim(name)) > 0
        and char_length(trim(slug)) > 0
        and dataset_count >= 0
    );

create policy "Allow anon and authenticated read detection_sessions"
    on public.detection_sessions
    for select
    to anon, authenticated
    using (true);

create policy "Allow anon and authenticated insert detection_sessions"
    on public.detection_sessions
    for insert
    to anon, authenticated
    with check (
        char_length(trim(media_name)) > 0
        and media_type in ('image', 'video')
        and mode in ('counting', 'tracking')
        and total_detected >= 0
    );

create policy "Allow anon and authenticated read enhancement_comparisons"
    on public.enhancement_comparisons
    for select
    to anon, authenticated
    using (true);

create policy "Allow anon and authenticated insert enhancement_comparisons"
    on public.enhancement_comparisons
    for insert
    to anon, authenticated
    with check (
        char_length(trim(image_name)) > 0
        and char_length(trim(best_method)) > 0
        and ground_truth_count >= 0
    );
